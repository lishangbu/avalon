package io.github.lishangbu.avalon.combat.model;

/** 固定回合阶段。枚举声明顺序即执行顺序，扩展只能处理阶段，不能插入或重排阶段。 */
public enum CombatPhase {

	/** 发布本轮公开状态；已锁定的敌方意图不得读取本轮玩家指令。 */
	OPEN,
	/** 核验此前锁定的敌方意图，记录其原始招式和目标。 */
	INTENT,
	/** 核验完整指令及外部资源快照，不产生真实资产副作用。 */
	COMMANDS,
	/** 登记免费补位并处理同批入场；成功补位者可保留本轮指令。 */
	REPLACEMENTS,
	/** 主动换宠先行，阶段开始后换宠队列不得再次排序。 */
	SWAPS,
	/** 按此时状态锁定普通行动顺序，同速抽样可追踪且不可重抽。 */
	ORDER,
	/** 逐条执行技能与反应，动作完成后检查唯一终局。 */
	ACTIONS,
	/** 战斗仍进行时统一结算一次回合末，不在终局后额外跳点。 */
	END,
	/** 清理到期状态并保存下一轮资格；终局时只执行收尾，不继续战斗。 */
	CLOSE

}
