import {clickWorldAction, closeNpc} from './support/npc'
import {expect, test} from '@playwright/test'
import {winStoryBattle} from './support/story-battle'

test('园圃观察与水源调查可在手机和桌面完成', async ({page}, info) => {
    test.skip(!process.env.AVALON_GARDEN_USER, '需要隔离数据库的开篇完成存档')
    test.setTimeout(180_000)
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await page.getByLabel('账号', {exact: true}).fill(`${process.env.AVALON_GARDEN_USER}_${info.project.name}`)
    await page.getByLabel('密码', {exact: true}).fill('Garden-browser-1234')
    await page.getByRole('button', {name: '进入冒险', exact: true}).click()
    await expect(page.getByText('今天要做的事', {exact: true})).toHaveCount(0)
    const click = async (name: string) => clickWorldAction(page, name)
    async function move(name: string) {
        await closeNpc(page)
        await click(name)
        await expect(page.getByRole('button', {name: `${name}，当前位置`, exact: true})).toBeVisible()
    }
    async function claim(name: string) {
        await click(name)
        const sheet = page
            .locator('ion-modal')
            .filter({visible: true})
            .filter({has: page.locator('ion-title').filter({hasText: /^对话$/})})
        await sheet.getByRole('button', {name: '继续', exact: true}).click()
        await expect(sheet).toHaveCount(0)
        await closeNpc(page)
    }
    await move('诺姆园圃')
    await expect(page.getByRole('button', {name: '查看往年花期表', exact: true})).toHaveCount(0)
    await claim('接取任务')
    // 主线只突出一项远程指引，主动追踪本次园圃委托，不依赖默认的罗温任务。
    await page.goto('/quests')
    const garden = page.locator('article').filter({has: page.getByRole('heading', {name: '园圃的花期表', exact: true})})
    await garden.getByRole('button', {name: '追踪任务', exact: true}).click()
    await expect(garden.getByText('追踪中', {exact: true})).toBeVisible()
    await page.goto('/world')
    await click('查看往年花期表')
    await click('查看今年的花床')
    await claim('提交提早开的花记录')
    for (const label of ['观察遮阴样地', '观察临水样地', '观察高地样地']) await click(label)
    await claim('提交三处不同的春意记录')
    await click('观察访客往返路线')
    await click('记录花间停留点')
    await click('凡是在花床停留的幻兽都是害兽')
    await expect(page.getByText(/结论不能超出观察证据/)).toBeVisible()
    await click('访客在正常觅食授粉，花期原因还需调查')
    await claim('提交花间的访客记录')
    await expect(page.getByText('前往诺姆城外围，检查上游支流。', {exact: true})).toBeVisible()
    await page.reload()
    await move('诺姆城')
    await move('诺姆城外围')
    for (const label of ['检查上游支流', '检查园圃支流', '查看分水口的落枝']) await click(label)
    await click('已经证明整片园圃魔力失衡')
    await expect(page.getByText(/找到堵口能解释局部缺水/)).toBeVisible()
    await click('落枝影响局部供水，花期变化的原因仍待观察')
    await claim('确认水源调查记录')
    for (const label of ['辨认幼兽栖处边界', '勘查外围石坡']) await click(label)
    await click('沿外围石坡绕行，保留幼兽饮水通道')
    await expect(page.getByText('前往诺姆城外围，完成「守护园圃作业路线」战斗。', {exact: true})).toBeVisible()
    await expect(page.getByRole('button', {name: /守护园圃作业路线/})).toBeVisible()
    await page.screenshot({path: info.outputPath('garden-route.png'), fullPage: true})
    await closeNpc(page)
    await winStoryBattle(page, '守护园圃作业路线')
    await claim('确认绕巢作业路线安全')
    await move('诺姆城')
    await move('诺姆园圃')
    for (const label of ['为试验花床搭遮棚', '标记未处理的对照花床', '记录两块花床的处理方式']) await click(label)
    await claim('提交给花床换一点阴凉记录')
    await move('诺姆城')
    await move('诺姆城外围')
    await click('沿绕巢路线清理落枝')
    await page.reload()
    await move('诺姆城')
    await move('诺姆园圃')
    await click('核验花床旁的下游水流')
    await claim('提交清水重新经过记录')
    await click('比较叶片与花期记录')
    await click('复查授粉访客的活动')
    await click('水道通了，所有异常已经彻底解决')
    await expect(page.getByText(/再对照处理前后的记录/)).toBeVisible()
    await click('供水和局部状态改善，异常花期仍需持续观察')
    await claim('提交变化与没变的事记录')
    for (const label of ['核对花期表的观察日期', '核对样地与水路位置', '整理照料备注与后续安排']) await click(label)
    await claim('交接园圃花期表与照料安排')
    await move('诺姆城')
    await move('诺姆城外围')
    await claim('接取任务')
    await click('查看近邻小径旧路标')
    await claim('确认小径的旧路标记录')
    await move('诺姆旧径')
    for (const label of ['检查悬空落石', '检查坡边落石', '记录稳定的绕行地面']) await click(label)
    await claim('确认落石下面的空隙记录')
    await click('沿固定足印观察')
    await click('辨认幻兽活动口')
    await claim('确认幻兽也走这条路记录')
    await click('灌木活动口前的平地')
    await expect(page.getByText(/堆放区不能堵住活动口/)).toBeVisible()
    await click('稳定地面内侧的空地，避开活动口')
    await click('标记人行与幻兽通道边界')
    await claim('确认重新画一条线记录')
    // 恢复设施必须沿真实道路抵达，不能直接填充战斗资源。
    await move('诺姆城外围')
    await move('诺姆城')
    await move('诺姆城幻兽中心')
    await click('全队免费恢复')
    await move('诺姆城')
    await move('诺姆城外围')
    await move('诺姆旧径')
    await winStoryBattle(page, '窄口的守路者')
    await claim('确认窄口的守路者成果')
    for (const label of ['清理绕路入口碎石', '清理中段通路', '移开终点松石', '安放连续通行界标']) await click(label)
    await claim('确认松开的最后一块石头成果')
    await move('诺姆矿场外庭')
    await click('核查外庭回程标记')
    await claim('确认走到矿场外庭成果')
    await move('诺姆旧径')
    for (const label of ['复查幻兽通行口', '复查人行界标', '交接旧径维护记录']) await click(label)
    await claim('确认两边都留条路成果')
    await page.reload()
    await expect(page.getByRole('button', {name: '确认两边都留条路成果', exact: true})).toHaveCount(0)
    await move('诺姆矿场外庭')
    await move('诺姆旧径')
    await page.screenshot({path: info.outputPath('old-trail-complete.png'), fullPage: true})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
})
