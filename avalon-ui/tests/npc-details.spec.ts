import {expect, test} from '@playwright/test'
import {randomUUID} from 'node:crypto'

test('NPC状态、服务归属与共享详情', async ({page}, info) => {
    test.setTimeout(150_000)
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await page.getByRole('button', {name: '创建账号', exact: true}).click()
    const suffix = randomUUID().slice(0, 8)
    await page.getByLabel('账号', {exact: true}).fill(`npc_${suffix}`)
    await page.getByLabel('密码', {exact: true}).fill('Npc-details-1234')
    await page.getByRole('button', {name: '注册并进入'}).click()
    await page.getByLabel('角色名', {exact: true}).fill(`访客${suffix}`)
    await page.getByRole('button', {name: '踏上旅途'}).click()
    const modal = (name: string) =>
        page
            .locator('ion-modal')
            .filter({visible: true})
            .filter({has: page.locator('ion-title').filter({hasText: name})})
    async function move(name: string) {
        await page.getByRole('button', {name, exact: true}).click()
        await expect(page.getByRole('button', {name: `${name}，当前位置`, exact: true})).toBeVisible()
    }
    async function command(npc: string, label: string) {
        await modal(npc).getByRole('button', {name: label, exact: true}).click()
        await modal('对话').getByRole('button', {name: '继续', exact: true}).click()
        await expect(modal('对话')).toHaveCount(0)
    }
    async function close(npc: string) {
        await modal(npc).getByRole('button', {name: '关闭', exact: true}).click()
        await expect(modal(npc)).toHaveCount(0)
    }
    await move('石板路')
    await move('村中广场')
    await expect(page.getByRole('button', {name: '接取任务', exact: true})).toHaveCount(0)
    await page.getByRole('button', {name: '特林，可接取任务', exact: true}).click()
    await expect(modal('特林')).toContainText('庆典筹办人')
    await expect(modal('特林').getByRole('button', {name: '接取任务', exact: true})).toBeEnabled()
    await close('特林')
    await expect(page.getByRole('button', {name: '特林，可接取任务', exact: true})).toBeVisible()
    await page.getByRole('button', {name: '特林，可接取任务', exact: true}).click()
    await command('特林', '接取任务')
    await close('特林')
    await expect(page.getByRole('button', {name: '特林，可交付任务', exact: true})).toBeVisible()
    await page.getByRole('button', {name: '特林，可交付任务', exact: true}).click()
    await command('特林', '接受庆典准备')
    await close('特林')
    await move('村长家')
    await page.getByRole('button', {name: '阿德，可接取任务', exact: true}).click()
    await modal('阿德').getByText('查看物品奖励', {exact: true}).click()
    await modal('阿德').locator('summary').filter({hasText: '村长的介绍凭据'}).click()
    await expect(modal('阿德').getByLabel('详细说明')).toBeVisible()
    await command('阿德', '接取任务')
    await command('阿德', '听取远行建议')
    await close('阿德')
    await move('村中广场')
    await move('武器店')
    await expect(page.getByRole('button', {name: '商店', exact: true})).toHaveCount(0)
    await page.getByRole('button', {name: '布鲁诺，可接取任务', exact: true}).click()
    await command('布鲁诺', '接取任务')
    await command('布鲁诺', '领取木剑信物')
    await close('布鲁诺')
    await move('村中广场')
    await move('幻兽中心')
    await expect(page.getByRole('button', {name: '全队免费恢复', exact: true})).toHaveCount(0)
    await page.getByRole('button', {name: '梅莎，可接取任务', exact: true}).click()
    await command('梅莎', '接取任务')
    await command('梅莎', '与利爪猫结契')
    await command('梅莎', '接取任务')
    await expect(modal('梅莎').getByRole('button', {name: '保存出战安排', exact: true})).toBeDisabled()
    await page.screenshot({path: info.outputPath('npc-panel.png'), fullPage: true})
    await close('梅莎')
    await expect(page.getByRole('button', {name: '梅莎，任务进行中', exact: true})).toBeVisible()
    await page.reload()
    await expect(page.getByRole('button', {name: '梅莎，任务进行中', exact: true})).toBeVisible()
    await move('村中广场')
    await move('杂货铺')
    await page.getByRole('button', {name: '杂货铺掌柜', exact: true}).click()
    await modal('杂货铺掌柜').getByRole('button', {name: '商店', exact: true}).click()
    await expect(page).toHaveURL(/\/shop$/)
    await page
        .locator('summary')
        .filter({hasText: /^封印球I$/})
        .click()
    await expect(page.getByText('适用目标等级上限：10级；超出仍可尝试，但成功率衰减', {exact: true})).toBeVisible()
    await page.goto('/companions')
    await page
        .getByRole('button', {name: /利爪猫/})
        .first()
        .click()
    await expect(page.getByText(/会在溪边的岩石上磨利前爪/)).toBeVisible()
    await page.getByText('查看特性效果', {exact: true}).click()
    await expect(
        page
            .locator('details')
            .filter({has: page.locator('summary').filter({hasText: '查看特性效果'})})
            .getByLabel('详细说明'),
    ).toBeVisible()
    await page
        .locator('summary')
        .filter({hasText: /^水弹$/})
        .click()
    await expect(page.getByText('消耗魔力：12', {exact: true})).toBeVisible()
    await page.screenshot({path: info.outputPath('creature-details.png'), fullPage: true})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
})
