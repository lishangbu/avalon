import {clickWorldAction, closeNpc, revealWorldAction} from './support/npc'
import {expect, test} from '@playwright/test'
import {winStoryBattle} from './support/story-battle'

test('任务记录按整项任务归档并支持标签地点筛选', async ({page}, info) => {
    test.skip(!process.env.AVALON_ROWAN_USER, '由隔离数据库浏览器入口准备开篇完成存档')
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await page.getByLabel('账号', {exact: true}).fill(`${process.env.AVALON_ROWAN_USER}_${info.project.name}`)
    await page.getByLabel('密码', {exact: true}).fill('Rowan-browser-1234')
    await page.getByRole('button', {name: '进入冒险', exact: true}).click()
    await expect(page.getByRole('button', {name: '诺姆城，当前位置', exact: true})).toBeVisible()
    await page.goto('/quests')
    await expect(page.getByRole('heading', {name: '罗温重新开门', exact: true})).toBeVisible()
    await expect(page.getByRole('heading', {name: '园圃的花期表', exact: true})).toBeVisible()
    await expect(page.getByRole('heading', {name: '莎琳的出航名额', exact: true})).toHaveCount(0)
    const rowan = page.locator('article').filter({has: page.getByRole('heading', {name: '罗温重新开门', exact: true})})
    const garden = page.locator('article').filter({has: page.getByRole('heading', {name: '园圃的花期表', exact: true})})
    await expect(rowan.getByText('追踪中', {exact: true})).toBeVisible()
    await garden.getByRole('button', {name: '追踪任务', exact: true}).click()
    await expect(garden.getByText('追踪中', {exact: true})).toBeVisible()
    await expect(rowan.getByText('追踪中', {exact: true})).toHaveCount(0)
    await page.reload()
    await expect(garden.getByText('追踪中', {exact: true})).toBeVisible()
    await garden.getByRole('button', {name: '取消追踪', exact: true}).click()
    await page.reload()
    await expect(page.getByText('追踪中', {exact: true})).toHaveCount(0)
    await rowan.getByRole('button', {name: '追踪任务', exact: true}).click()
    await expect(rowan.getByText('追踪中', {exact: true})).toBeVisible()
    await page.goto('/world')
    await expect(page.getByText('橱窗里还缺什么', {exact: true})).toBeVisible()
    await expect(page.getByText('提早开的花', {exact: true})).toHaveCount(0)
    await page.goto('/quests')
    await page.getByLabel('标签', {exact: true}).selectOption('GUIDE')
    await expect(page.getByText('暂无符合条件的任务', {exact: true})).toBeVisible()
    await page.locator('ion-segment-button').filter({hasText: '已完成'}).click()
    const academy = page
        .locator('article')
        .filter({has: page.getByRole('heading', {name: '诺姆学院的课程', exact: true})})
    await expect(academy).toBeVisible()
    await expect(page.getByRole('heading', {name: '给伙伴留个位置', exact: true})).toBeVisible()
    await academy.getByText('任务步骤', {exact: true}).click()
    await expect(academy.locator('li')).toHaveCount(9)
    await expect(academy.getByText('我的职业办法 · 已完成', {exact: true})).toBeVisible()
    await page.getByLabel('地点', {exact: true}).selectOption('ACADEMY')
    await expect(academy).toBeVisible()
    await expect(page.locator('article')).toHaveCount(1)
    await page.screenshot({path: info.outputPath('quest-journal.png'), fullPage: true})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.reload()
    await page.locator('ion-segment-button').filter({hasText: '已完成'}).click()
    await expect(page.getByRole('heading', {name: '诺姆学院的课程', exact: true})).toBeVisible()
    expect(errors).toEqual([])
})

test('罗温筹备任务在手机与桌面均可操作', async ({page}, info) => {
    test.skip(!process.env.AVALON_ROWAN_USER, '由隔离数据库浏览器入口准备开篇完成存档')
    test.setTimeout(180_000)
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await page.getByLabel('账号', {exact: true}).fill(`${process.env.AVALON_ROWAN_USER}_${info.project.name}`)
    await page.getByLabel('密码', {exact: true}).fill('Rowan-browser-1234')
    await page.getByRole('button', {name: '进入冒险', exact: true}).click()
    async function click(name: string) {
        await clickWorldAction(page, name)
    }
    async function move(name: string) {
        await closeNpc(page)
        await click(name)
        await expect(page.getByRole('button', {name: `${name}，当前位置`, exact: true})).toBeVisible()
    }
    async function talk(name: string) {
        await click(name)
        const sheet = page
            .locator('ion-modal')
            .filter({visible: true})
            .filter({has: page.locator('ion-title').filter({hasText: /^对话$/})})
        await sheet.getByRole('button', {name: '继续', exact: true}).click()
        await expect(sheet).toHaveCount(0)
        await closeNpc(page)
    }
    await move('罗温杂货铺')
    await revealWorldAction(page, '接取任务')
    const conversation = page.getByLabel('现场交谈').locator('details').filter({hasText: '橱窗里还缺什么'})
    // 展开文字不会自动接受委托；阶段改变后重新展开对应的现场交谈。
    await conversation.locator('summary').click()
    await expect(conversation.locator('p')).toBeVisible()
    const offer = await conversation.locator('p').textContent()
    await expect(page.getByRole('button', {name: '接取任务', exact: true})).toBeEnabled()
    await page.screenshot({path: info.outputPath('quest-conversation.png'), fullPage: true})
    await talk('接取任务')
    await revealWorldAction(page, '与罗温确认店铺现况')
    await conversation.locator('summary').click()
    await expect(conversation.locator('p')).not.toHaveText(offer!)
    await expect(page.getByRole('region', {name: '相关资料'}).getByText('药品架', {exact: true})).toBeVisible()
    await expect(page.getByRole('region', {name: '相关资料'}).getByRole('button')).toHaveCount(0)

    await talk('与罗温确认店铺现况')
    await move('诺姆城')

    await talk('整理旅人需求')
    await move('罗温杂货铺')
    await revealWorldAction(page, '可售货架')
    const scene = (title: string) =>
        page
            .getByLabel('现场行动')
            .locator('.row')
            .filter({has: page.getByText(title, {exact: true})})
    await scene('整理断裂扣环').getByRole('button', {name: '可售货架', exact: true}).click()
    await expect(page.getByText(/再看一眼物品的公开状况/)).toBeVisible()
    for (const [name, choice] of [
        ['整理密封药瓶', '可售货架'],
        ['整理脱线背包', '待修货架'],
        ['整理断裂扣环', '报废回收箱'],
    ])
        await scene(name!).getByRole('button', {name: choice!, exact: true}).click()
    await talk('确认还能用的旧货')
    await page.reload()
    await move('诺姆城')
    await move('诺姆城外围')
    await move('河口商道')

    await click('少量药品、封印球、修补布与扣环')
    await talk('确认商道上的第一批货')
    await move('诺姆城外围')

    await click('走高地路，经过休息点回城')
    await talk('确认看得见的路况')
    await revealWorldAction(page, '交付试送货包并签收')
    await expect(page.getByText('第一次安全试送', {exact: true})).toBeVisible()
    await expect(page.getByText('前往河口商道，领取试送货包。', {exact: true})).toBeVisible()
    await page.screenshot({path: info.outputPath('rowan-route.png'), fullPage: true})
    await closeNpc(page)
    await move('河口商道')
    await click('领取试送货包')
    await page.reload()
    await move('诺姆城外围')
    await revealWorldAction(page, '交付试送货包并签收')
    await expect(page.getByRole('button', {name: '交付试送货包并签收', exact: true})).toBeDisabled()
    await closeNpc(page)
    await winStoryBattle(page, '护送罗温的试送货包')
    await talk('交付试送货包并签收')
    await move('诺姆城')
    await move('罗温杂货铺')
    for (const label of ['摆放药品价签', '摆放封印球价签', '摆放修补用品价签']) await click(label)
    await talk('确认一张诚实的价签')
    await click('给他生命药，让他自己试试')
    await expect(page.getByText(/再看看顾客的需求和货品说明/)).toBeVisible()
    await click('带他到魔力药货架，并补上用途标牌')
    await click('说明封印球II支持11至20级，不保证捕获')
    await click('把漏壶隔离待修，从任务库存换一只完好的')
    await talk('确认试营业的半天')
    await talk('确认罗温重新开门')
    await page.reload()
    await expect(page.getByRole('button', {name: '确认罗温重新开门', exact: true})).toHaveCount(0)
    await page.screenshot({path: info.outputPath('rowan-complete.png'), fullPage: true})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
})
