import {expect, test} from '@playwright/test'
import {clickWorldAction, closeNpc, revealWorldAction} from './support/npc'
import {winStoryBattle} from './support/story-battle'

test('幼兽团聚在手机与桌面完成，资料直接展示且实际行动不可跳过', async ({page}, info) => {
    test.skip(!process.env.AVALON_REUNION_USER, '需要隔离数据库的试航结束存档')
    test.setTimeout(180_000)
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/')
    await page.getByLabel('账号', {exact: true}).fill(`${process.env.AVALON_REUNION_USER}_${info.project.name}`)
    await page.getByLabel('密码', {exact: true}).fill('Reunion-browser-1234')
    const loaded = page.waitForResponse((response) => response.url().endsWith('/api/quests'))
    await page.getByRole('button', {name: '进入冒险', exact: true}).click()
    await loaded
    const click = (name: string) => clickWorldAction(page, name)
    async function move(name: string) {
        await closeNpc(page)
        await click(name)
        await expect(page.getByRole('button', {name: `${name}，当前位置`, exact: true})).toBeVisible()
    }
    async function claim(name: string) {
        await click(name)
        const sheet = page
            .locator('ion-modal')
            .filter({visible: true})
            .filter({has: page.locator('ion-title').filter({hasText: /^对话$/})})
        await sheet.getByRole('button', {name: '继续', exact: true}).click()
        await expect(sheet).toHaveCount(0)
        await closeNpc(page)
    }
    await claim('接取任务')
    for (const location of ['温蒂妮城', '港湾照护站']) await move(location)
    await revealWorldAction(page, '与佩罗确认团聚委托')
    const notes = page.getByRole('region', {name: '相关资料'})
    await expect(notes.getByText('佩罗的照护簿', {exact: true})).toBeVisible()
    await expect(notes.getByRole('button')).toHaveCount(0)
    await page.screenshot({path: info.outputPath('care-notes.png'), fullPage: true})
    await claim('与佩罗确认团聚委托')
    await click('它一定被遗弃了，长期留在照护站')
    await expect(page.getByText(/还没有被遗弃的依据/)).toBeVisible()
    await expect(page.getByRole('button', {name: '确认幼兽回应呼声的线索', exact: true})).toBeDisabled()
    await click('它在回应浅滩的群体，先寻找同伴')
    await claim('确认幼兽回应呼声的线索')
    await move('银沙浅滩')
    await expect(page.getByRole('region', {name: '地点资料'}).getByText('浅滩群体记录', {exact: true})).toBeVisible()
    await click('内侧岩边：长单声、涨潮活动')
    await expect(page.getByText(/内侧岩边群体的呼声和潮时都不相符/)).toBeVisible()
    await click('外侧浅水带：短促双声、退潮活动')
    await claim('记下与幼兽相符的群体')
    await move('近岸望潮台')
    await click('西侧近槽：距离短，但水深且向港内回流')
    await expect(page.getByText(/东侧沙脊才是浅水退潮路线/)).toBeVisible()
    await click('东侧沙脊：水浅，退潮向外，沿岸通行')
    await claim('确认团聚的浅水路线')
    for (const location of ['银沙浅滩', '港湾照护站']) await move(location)
    await click('与佩罗分工安排放归')
    await claim('确认与佩罗共同放归的安排')
    await move('银沙浅滩')
    await expect(page.getByRole('button', {name: '清出浅滩引导口', exact: true})).toHaveCount(0)
    await expect(page.getByRole('button', {name: '清理战后的引导出口', exact: true})).toHaveCount(0)
    await click('清除浅滩废绳网')
    await page.reload()
    await expect(page.getByRole('button', {name: '银沙浅滩，当前位置', exact: true})).toBeVisible()
    await winStoryBattle(page, '清出浅滩引导口')
    await expect(page.getByRole('button', {name: '确认浅滩引导口安全', exact: true})).toBeDisabled()
    await click('清理战后的引导出口')
    await claim('确认浅滩引导口安全')
    await expect(page.getByRole('button', {name: '清出浅滩引导口', exact: true})).toHaveCount(0)
    await click('抱着幼兽直接穿过西侧深槽')
    await expect(page.getByText(/不要把幼兽抱进深槽/)).toBeVisible()
    await click('沿东侧引导绳让出距离，让它循声前行')
    await expect(page.getByRole('button', {name: '确认幼兽主动回到群体', exact: true})).toBeDisabled()
    await click('让出通道等待幼兽团聚')
    await claim('确认幼兽主动回到群体')
    await expect(page.getByRole('region', {name: '地点资料'}).getByText('浅滩的团聚记录', {exact: true})).toBeVisible()
    await click('设置东侧浅水路线标记')
    await move('港湾照护站')
    await revealWorldAction(page, '与佩罗完成放归交接')
    await expect(page.getByRole('button', {name: '与佩罗完成放归交接', exact: true})).toBeDisabled()
    await click('向佩罗登记放归与标记')
    await claim('与佩罗完成放归交接')
    await page.reload()
    await page.getByRole('region', {name: '在场人物'}).getByRole('button', {name: '佩罗', exact: true}).click()
    await expect(page.getByRole('region', {name: '相关资料'}).getByText('完成后的照护簿', {exact: true})).toBeVisible()
    await expect(page.getByRole('button', {name: '与佩罗完成放归交接', exact: true})).toHaveCount(0)
    await page.screenshot({path: info.outputPath('reunion-complete.png'), fullPage: true})
    await move('银沙浅滩')
    await expect(page.getByRole('button', {name: '探索银沙浅滩', exact: true})).toBeVisible()
    await expect(page.getByRole('button', {name: '清出浅滩引导口', exact: true})).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(errors).toEqual([])
})
